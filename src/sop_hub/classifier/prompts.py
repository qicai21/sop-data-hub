from __future__ import annotations

from typing import Mapping


def build_classify_prompt(cards: Mapping[str, str], *, hint: str = "") -> str:
    ordered_cards = "\n".join(f"### {name}\n{cards[name]}" for name in cards)
    return f"""你是一个专业的业务单据与视觉分析专家。请分析上传的图片，并根据预设的类别进行分类。

## 任务说明
你的任务是根据图片的视觉特征（版式、标题、内容物、拍摄视角）将其归入最合适的类别。请专注于观察图片中的实质信息。

## 识别原则
1. **深度观察**：优先通过标题（如“检、装车通知单”、“疏港检、装车通知单”、“检车清单”）、特定的表格列（如“车号”、“箱号”）或现场物体（如“敞车”、“货垛”）进行判断。
2. **逻辑锚点**：
   - 如果最左侧一列出现“整车”、“小计”、“集装箱”，直接判定为“请车表”。
   - 如果标题包含“检、装车通知单”或“疏港检、装车通知单”，直接判定为“检装车通知单”。
3. **合理判定**：不要因为图片稍微模糊或光线不足就轻易放弃分类。只要有 60% 以上的视觉证据支持某一类别，请优先输出该类别。
3. **区分特征**：
   - 制式打印表单（印刷体、对齐的横线） vs. 手写单据（手写体、书写不规整）。
   - 实景照片（户外、机器、人员、光影真实） vs. 扫描/文档拍屏。

## 类别库与特征定义
{ordered_cards}

{hint}

## 输出指令 (非常重要)
请直接输出 JSON 结果，严禁包含任何解释文字、Markdown 代码块、或者前序分析。
输出格式如下：
{{"category":"","confidence":0.0,"detected_title":"","evidence":""}}
"""



